CREATE TABLE sku (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE warehouse (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    route_priority INT NOT NULL UNIQUE,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE bin (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
    type VARCHAR(16) COLLATE utf8mb4_bin NOT NULL,
    pick_priority INT NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uq_bin_warehouse_code UNIQUE (warehouse_id, code),
    CONSTRAINT fk_bin_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (id),
    CONSTRAINT ck_bin_type CHECK (type IN ('RECEIVING', 'PICKABLE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
